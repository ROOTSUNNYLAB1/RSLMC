import { Router, jsonError, json } from "../shared/http";
import { SESSION_COOKIE, validateSession } from "../auth";
import { rateLimit } from "../security/ratelimit";
import { checkOrigin } from "../security/origin";
import { buildContext } from "./context";
import { registerAuthRoutes } from "./auth-routes";
import { registerServerRoutes } from "./server-routes";
import { registerFileRoutes } from "./file-routes";
import { registerAdminRoutes } from "./admin-routes";
import { registerPanelRoutes } from "./panel-routes";
import { registerNodeRoutes } from "./node-routes";
import { isAgentKey, nodeControllerUser, bumpAccepted, recordAgentEvent } from "../nodes/agent";
import { proxyServerRequest } from "../nodes/proxy";

export const api = new Router();
registerAuthRoutes(api);
registerServerRoutes(api);
registerFileRoutes(api);
registerAdminRoutes(api);
registerPanelRoutes(api);
registerNodeRoutes(api);

/** Routes that are reachable without a session. */
const PUBLIC_ROUTES = new Set([
  "POST /api/auth/login",
  "POST /api/auth/register",
  "GET /api/auth/registration",
  "POST /api/auth/password/check",
  "GET /api/auth/oauth/providers",
  "POST /api/auth/oauth/complete",
  "GET /api/auth/me",
  "GET /api/setup/status",
  "GET /api/setup/enforcement",
]);

const PUBLIC_ROUTE_PATTERNS = new Set([
  "GET /api/auth/oauth/[^/]+/start",
  "GET /api/auth/oauth/[^/]+/callback",
]);

const SAFE_METHODS = new Set(["GET", "HEAD", "OPTIONS"]);

export async function handleApiRequest(req: Request, url: URL, clientIpValue: string): Promise<Response | null> {
  /*
   * A controller panel talks to a node with `Authorization: Bearer <agent key>`. A node with no key
   * configured ignores this entirely and behaves as a stand-alone panel.
   *
   * The key is accepted on every /api path, not just /api/agent/*: the controller forwards ordinary
   * per-server requests (files, console, power, backups) to the node's own routes, and those are the
   * routes that actually know how to do the work. That is the trade-off of the design — a node key is
   * equivalent to the node's administrator — and it is why the key is generated by the controller,
   * stored hashed on the node, rotatable from either side, and required to be at least 24 characters.
   */
  const bearer = bearerToken(req);
  /* istanbul ignore next -- exercised by tests/nodes.test.ts */
  if (bearer && isAgentKey(bearer)) {
    bumpAccepted();
    recordAgentEvent("request", `${req.method} ${url.pathname}`);
    const matchAgent = api.match(req.method, url.pathname);
    if (!matchAgent) return null;
    const ctx = buildContext(
      new Request(req.url, {
        method: req.method,
        headers: (() => { const h = new Headers(req.headers); h.set("x-rslmc-client-ip", clientIpValue); return h; })(),
        body: SAFE_METHODS.has(req.method) ? undefined : req.body,
        // @ts-expect-error Bun supports duplex for streaming request bodies
        duplex: "half",
      }),
      url,
      matchAgent.params,
      req.headers.get("cookie"),
    );
    ctx.user = nodeControllerUser();
    try {
      return await matchAgent.route.handler(ctx);
    } catch (error) {
      return jsonError(error);
    }
  }

  /*
   * A server that lives on another machine is not managed here: the request is forwarded to the node
   * that owns it, after this panel has checked the caller's permissions. Local servers fall through
   * to normal routing below.
   */
  const proxied = await proxyServerRequest(req, url, clientIpValue);
  if (proxied) return proxied;

  const match = api.match(req.method, url.pathname);
  if (!match) return null;

  const cookiesHeader = req.headers.get("cookie");
  const ctx = buildContext(
    new Request(req.url, {
      method: req.method,
      headers: (() => {
        const headers = new Headers(req.headers);
        headers.set("x-rslmc-client-ip", clientIpValue);
        return headers;
      })(),
      body: SAFE_METHODS.has(req.method) ? undefined : req.body,
      // @ts-expect-error Bun supports duplex for streaming request bodies
      duplex: "half",
    }),
    url,
    match.params,
    cookiesHeader,
  );

  try {
    // --- Rate limiting for mutating endpoints -------------------------------------------
    if (!SAFE_METHODS.has(req.method)) {
      const limiter = rateLimit(`api:${clientIpValue}:${url.pathname}`, 120, 60_000);
      if (!limiter.allowed) {
        return json({ error: { code: "rate_limited", message: `Slow down — retry in ${limiter.retryAfterSeconds}s` } }, {
          status: 429, headers: { "retry-after": String(limiter.retryAfterSeconds) },
        });
      }
    }

    // --- Session ------------------------------------------------------------------------
    const token = ctx.cookies[SESSION_COOKIE];
    if (token) {
      const session = validateSession(token);
      if (session) {
        ctx.user = session.user;
        ctx.session = { id: session.sessionId, csrfToken: session.csrfToken };
      }
    }

    const key = `${req.method} ${url.pathname}`;
    /*
     * Exact matches first (cheap), then the same set expressed as patterns so parameterised public
     * routes (`/api/auth/oauth/:provider/start`) are recognised instead of being bounced to the
     * login page with a 401.
     */
    const isPublic = PUBLIC_ROUTES.has(key)
      || [...PUBLIC_ROUTE_PATTERNS].some((pattern) => new RegExp(`^${pattern}$`).test(key));
    const needsAuth = !isPublic && !(req.method === "GET" && url.pathname === "/api/auth/me");
    if (needsAuth && !ctx.user) {
      return json({ error: { code: "unauthorized", message: "Authentication required" } }, { status: 401 });
    }

    // --- CSRF ---------------------------------------------------------------------------
    if (!SAFE_METHODS.has(req.method) && !isPublic) {
      const header = req.headers.get("x-csrf-token");
      if (!header || !ctx.session || header !== ctx.session.csrfToken) {
        return json({ error: { code: "csrf_invalid", message: "Invalid or missing CSRF token. Reload the panel and try again." } }, { status: 403 });
      }
      /*
       * Compare hosts, not whole origin strings: behind TLS termination the panel only ever sees
       * plain HTTP from the proxy, so comparing `https://panel.example.com` with
       * `http://panel.example.com` refused every write on a perfectly good deployment. See
       * src/security/origin.ts for the rules; a different hostname is still refused.
       */
      const decision = checkOrigin({
        origin: req.headers.get("origin"),
        url,
        headers: req.headers,
        publicUrl: process.env.RSLMC_PUBLIC_URL ?? null,
      });
      if (!decision.allowed) {
        // Make the refusal diagnosable instead of a bare 403: the operator can see which host was
        // presented, which hosts the panel accepts, and whether a proxy is rewriting anything.
        console.log(
          `[rslmc] 403 origin_invalid ${req.method} ${url.pathname} — origin=${req.headers.get("origin")} ` +
          `host=${req.headers.get("host")} x-forwarded-host=${req.headers.get("x-forwarded-host") ?? "-"} ` +
          `accepted=${decision.considered.join(",") || "-"}`,
        );
        return json(
          {
            error: {
              code: "origin_invalid",
              message:
                `Cross-origin request rejected: the browser sent Origin ${req.headers.get("origin")}, but this ` +
                `panel answers on ${decision.considered.join(", ") || "an unknown host"}. If a reverse proxy or ` +
                "tunnel sits in front of RSLMC, set RSLMC_PUBLIC_URL to the address you opened the panel on.",
            },
          },
          { status: 403 },
        );
      }
    }

    const response = await match.route.handler(ctx);
    return response;
  } catch (error) {
    return jsonError(error);
  }
}

function bearerToken(req: Request): string | null {
  const header = req.headers.get("authorization");
  if (!header) return null;
  const match = /^Bearer\s+(.+)$/i.exec(header.trim());
  return match ? match[1]!.trim() : null;
}

export function describeRoutes(): string[] {
  return api.list();
}
